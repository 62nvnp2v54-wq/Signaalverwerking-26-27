from gpiozero import LED
from time import sleep

led0 = LED(4)
led1 = LED(17)
led2 = LED(18)
led3 = LED(27)
led4 = LED(22)
led5 = LED(23)

while True:
    led0.on()
    sleep(0.2)
    led0.off()
    led1.on()
    sleep(0.2)
    led1.off()
    led2.on()
    sleep(0.2)
    led2.off()
    led3.on()
    sleep(0.2)
    led3.off()
    led4.on()
    sleep(0.2)
    led4.off()
    led5.on()
    sleep(0.2)
    led5.off()
    led4.on()
    sleep(0.2)
    led4.off()
    led3.on()
    sleep(0.2)
    led3.off()
    led2.on()
    sleep(0.2)
    led2.off()
    led1.on()
    sleep(0.2)
    led1.off()